  const gurobiAvailable=capabilities.solver_capabilities.find(s=>s.id==='gurobi').available;
  if(gurobiAvailable) {
    await page.locator('#forecastSolver').selectOption('gurobi');
    await page.locator('#forecastThreads').fill('2');await page.locator('#forecastThreads').dispatchEvent('change');
    await page.locator('#forecastTimeLimit').fill('30');await page.locator('#forecastTimeLimit').dispatchEvent('change');
  }
  await page.locator('#forecastGenerate').click();
  await page.waitForFunction(() => document.querySelector('#forecastStatus').textContent.includes('边界已生成'));
  let state = await get(); assert.equal(state.job.scenarios.length, 4); assert.equal(state.job.scenarios[0].config.days.length, 8);
  assert.equal(state.job.config.marginals[0].center.length, 8);
  assert.match(await page.locator('#forecastBoundaryPreview').textContent(), /2028-02-08（仅预测）/);
  assert.equal(state.job.config.marginals[0].center[0], 2);
  assert.equal(await page.getByLabel('Canvas 日期', { exact: true }).locator('option').count(), 7);
  assert.equal(await page.locator('#marketCanvas').getAttribute('data-valid'), 'false');
  assert.match(await page.locator('#forecastBoundaryPreview').textContent(), /2028-02-07/);
  await page.getByRole('button',{name:'预览场景当日边界 1',exact:true}).click();
