  const expected = day.nodes[0].deficit_mw[0]-day.nodes[0].surplus_mw[0];
  assert.ok(Math.abs(Number(await page.locator('[data-market-ref="buses:1"]').getAttribute('data-value'))-expected)<1e-6);
  assert.match(await page.locator('#marketCanvasContext').textContent(), new RegExp(`场景 ${affected.id+1}`));
  await page.getByLabel('Canvas 场景', { exact: true }).selectOption('0');
  const reference = state.job.scenarios[0].days[day.day].nodes[0];
  assert.ok(Math.abs(Number(await page.locator('[data-market-ref="buses:1"]').getAttribute('data-value'))-(reference.deficit_mw[0]-reference.surplus_mw[0]))<1e-6);
  await page.getByLabel('Canvas 场景', { exact: true }).selectOption(String(affected.id));
  assert.match(await page.locator('#operationCauses').textContent(), /恢复因素/);
  assert.ok(day.counterfactuals.some(c=>c.reference_value===2&&c.valid));
  const download = await (await fetch(url+'/api/session/market_forecast?export=1')).json(); assert.equal(download.job.base.buses.length,1);
  await mkdir(path.join(root,'output/market-forecast'),{recursive:true});
