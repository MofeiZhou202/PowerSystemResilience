  assert.equal((await post({action:'step',run_id:start.data.run_id,scenario:0,day:0})).status,400);
  assert.deepEqual(errors,[]);
  console.log('Forecast GUI/API passed: seven-day generation, probabilistic and interval scenarios, daily clearing, analytic statistics, reference causes, export/reload/cancel/conflict, mobile.');
