ComponentRuntimeSemantics component(
    const char* type, const char* path, const char* terminal,
    const char* units, const char* sign, const char* owner,
    const char* result, std::initializer_list<WorkflowFidelity> workflows,
    const char* boundary) {
  return {type,
          path,
          "Stable authored component .index; vector position and graph index are execution-only",
          terminal,
          units,
          sign,
          owner,
          result,
          workflows,
          boundary};
}

WorkflowFidelity wf(const char* workflow, F fidelity, const char* role) {
  return {workflow, fidelity, role};
}

