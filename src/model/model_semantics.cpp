const ComponentRuntimeSemantics* find_component_runtime_semantics(
    std::string_view collection_path) {
  const auto& rows = components();
  const auto it = std::find_if(rows.begin(), rows.end(), [&](const auto& row) {
    return row.collection_path == collection_path;
  });
  return it == rows.end() ? nullptr : &*it;
}

const ModuleDataContract* find_module_data_contract(
    std::string_view source_module) {
  const auto& rows = modules();
  const auto it = std::find_if(rows.begin(), rows.end(), [&](const auto& row) {
    return row.source_module == source_module;
  });
  return it == rows.end() ? nullptr : &*it;
}

std::string to_string(RuntimeFidelity fidelity) {
  switch (fidelity) {
    case F::Exact: return "exact";
    case F::Equivalent: return "equivalent";
    case F::Aggregated: return "aggregated";
    case F::BoundaryInjection: return "boundary-injection";
    case F::Projected: return "projected";
    case F::Unsupported: return "unsupported";
    case F::NotApplicable: return "not-applicable";
  }
  return "unsupported";
}

