std::string sci(double v) {
  std::ostringstream os;
  os << std::scientific << std::setprecision(2) << v;
  return os.str();
}

std::string latex_escape(const std::string& s) {
  std::string out;
  out.reserve(s.size() + 8);
  for (char c : s) {
    if (c == '_' || c == '%' || c == '#' || c == '&') out.push_back('\\');
    out.push_back(c);
  }
  return out;
}

const char* mark(bool ok) { return ok ? "\\checkmark" : "$\\times$"; }

