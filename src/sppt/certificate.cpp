// ── Certificate renderers ────────────────────────────────────────────────────
bool Certificate::all_pass() const {
  for (const auto& r : rows) {
    if (!r.pf_pass) return false;
    if (r.independent_supported && !r.independent_pass) return false;
    if (r.opf_converged && !r.opf_pass) return false;
  }
  return true;
}

int Certificate::pass_count() const {
  int n = 0;
  for (const auto& r : rows)
    if (r.pf_pass && (!r.independent_supported || r.independent_pass) &&
        (r.opf_pass || !r.opf_converged)) ++n;
  return n;
}

std::string Certificate::to_csv() const {
  std::ostringstream os;
  os << "case,n_ac_bus,n_dc_bus,pf_converged,pipeline_residual,pipeline_pass,"
        "independent_supported,independent_residual,independent_pass,"
        "approximate_merges,attribution_total,opf_converged,"
        "opf_dual_residual,opf_pass,tolerance,note\n";
  for (const auto& r : rows) {
    os << r.case_name << ',' << r.n_ac_bus << ',' << r.n_dc_bus << ','
       << (r.pf_converged ? 1 : 0) << ',' << sci(r.pf_residual) << ','
       << (r.pf_pass ? 1 : 0) << ',' << (r.independent_supported ? 1 : 0) << ','
       << sci(r.independent_residual) << ',' << (r.independent_pass ? 1 : 0) << ','
       << r.approximate_merges << ',' << (r.attribution_total ? 1 : 0) << ','
       << (r.opf_converged ? 1 : 0) << ','
       << sci(r.opf_dual_residual) << ',' << (r.opf_pass ? 1 : 0) << ','
       << sci(r.tolerance) << ',' << r.note << '\n';
  }
  return os.str();
}

