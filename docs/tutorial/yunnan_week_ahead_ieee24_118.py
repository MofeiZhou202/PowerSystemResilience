#!/usr/bin/env python3
"""Multi-resolution IEEE RTS-24 / IEEE-118 week-ahead risk benchmark.

This is a research prototype, not a production market-clearing implementation.
It preserves the information structure proposed in the accompanying technical
document while keeping the stochastic recourse problems linear:

* D+1: 96 x 15-minute periods;
* D+2--D+3: 48 x hourly periods;
* D+4--D+7: 12 x peak/flat/valley eight-hour blocks;
* RTS-24: detailed local DC network for D+1--D+3;
* IEEE-118: a hidden benchmark environment that synthesizes observable market
  outcomes; the Yunnan optimizer never receives external buses, branches,
  generators, loads, bids, or dispatch decisions;
* local SCUC and hydro vibration-zone results are represented by fixed market
  templates, so each conditional operating-scenario recourse is an LP.

The IEEE-118 data are read from this repository's production case builder.  The
RTS-24 skeleton follows the public IEEE RTS / MATPOWER 24-bus topology; resource
classification and all Yunnan-oriented additions are synthetic and explicitly
identified below.
"""

