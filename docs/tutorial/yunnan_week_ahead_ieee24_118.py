def joint_scenarios() -> List[JointScenario]:
    markets = {scenario.name: scenario for scenario in market_simulation_scenarios()}
    result = [
        JointScenario(markets[physical.parent_market], physical)
        for physical in physical_forecast_scenarios()
    ]
    if abs(sum(scenario.probability for scenario in result) - 1.0) > 1e-12:
        raise RuntimeError("joint market/physical scenario probabilities do not sum to one")
    return result


def validate_uncertainty_models() -> None:
    markets = market_simulation_scenarios()
    physical = physical_forecast_scenarios()
    if abs(sum(s.probability for s in markets) - 1.0) > 1e-12:
        raise RuntimeError("market scenario probabilities do not sum to one")
    for market in markets:
        conditional = [s for s in physical if s.parent_market == market.name]
        if abs(sum(s.conditional_probability for s in conditional) - 1.0) > 1e-12:
            raise RuntimeError(f"conditional forecast probabilities fail for {market.name}")
    trajectory_fields = (
        "load_factor_by_day", "wind_factor_by_day", "solar_factor_by_day",
        "inflow_factor_by_day", "dc_factor_by_day",
    )
    for scenario in physical:
        for field in trajectory_fields:
            values = getattr(scenario, field)
            if len(values) != 7 or not np.all(np.isfinite(values)) or min(values) <= 0:
                raise RuntimeError(f"invalid {field} trajectory in {scenario.name}")


def summarize_market_simulation(
    package: Package, external_proxy: YunnanObservableProxy,
) -> List[Dict[str, float | str]]:
    steps = time_grid()
    near = np.asarray([step.day <= 2 for step in steps])
    summaries: List[Dict[str, float | str]] = []
    for market in market_simulation_scenarios():
        commitment, _, hydro_high, q_schedule = _market_template(
            steps, market, package, external_proxy
        )
        near_q = q_schedule[near].sum(axis=1)
        summaries.append({
            "market": market.name,
            "probability": market.probability,
            "mean_committed_thermal_units_d1_d3": float(commitment[near].sum(axis=1).mean()),
            "mean_active_hydro_zones_d1_d3": float((hydro_high[near] > 0).sum(axis=1).mean()),
            "mean_dc_schedule_mw_d1_d3": float(near_q.mean()),
            "p10_dc_schedule_mw_d1_d3": float(np.quantile(near_q, .10)),
            "p90_dc_schedule_mw_d1_d3": float(np.quantile(near_q, .90)),
        })
    return summaries


