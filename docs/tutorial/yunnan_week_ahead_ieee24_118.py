def time_grid() -> List[Step]:
    steps: List[Step] = []
    for q in range(96):
        steps.append(Step(len(steps), 0, q / 4.0, .25, "15min"))
    for day in (1, 2):
        for hour in range(24):
            steps.append(Step(len(steps), day, float(hour), 1.0, "1h"))
    for day in range(3, 7):
        for hour in (4.0, 12.0, 20.0):
            steps.append(Step(len(steps), day, hour, 8.0, "block"))
    assert len(steps) == 156
    return steps


def _load_hidden_ieee118_truth() -> Tuple[List[Generator], List[Branch], np.ndarray]:
    """Load hidden benchmark truth; never call this from Yunnan optimization."""
    source = (ROOT / "src" / "scuc" / "case_builder.cpp").read_text()
    section = source[source.index("SCUCInput build_ieee118_case"):]

    gen_text = section[section.index("const GenSpec gens[]"):section.index("for (const auto& gs : gens)")]
    gens: List[Generator] = []
    for line in gen_text.splitlines():
        match = re.search(r'\{"(G\d+)",\s*(.*?)\},', line)
        if not match:
            continue
        values = [float(v.strip()) for v in match.group(2).split(",")]
        bus, pmin, pmax = int(values[0]), values[1], values[2]
        a_coeff, b_coeff = values[-2], values[-1]
        marginal_cost = b_coeff + a_coeff * pmax
        gens.append(Generator(match.group(1), bus, pmin, pmax, marginal_cost))

    branch_text = section[section.index("const BrSpec branches[]"):section.index("static_assert", section.index("const BrSpec branches[]"))]
    branches = [
        Branch(int(f), int(t), float(x), float(rating))
        for f, t, x, rating in re.findall(
            r"\{\s*(\d+),\s*(\d+),\s*([0-9.]+),\s*([0-9.]+)\s*\}", branch_text
        )
    ]

    load_text = section[section.index("const LoadSpec loads[]"):section.index("for (const auto& ls : loads)")]
    loads = np.zeros(118)
    for bus, value in re.findall(r"\{\s*(\d+),\s*([0-9.]+)\s*\}", load_text):
        loads[int(bus)] = float(value)
    # The local builder's explicit array contains 98 non-zero load buses even
    # though its header comment says 99; use the actual executable data.
    if (len(gens), len(branches), int(np.count_nonzero(loads))) != (54, 186, 98):
        raise RuntimeError(
            "IEEE-118 parser no longer matches case_builder.cpp: "
            f"gens={len(gens)}, branches={len(branches)}, loads={np.count_nonzero(loads)}"
        )
    return gens, branches, loads


def _network_matrix(n_bus: int, branches: Sequence[Branch]) -> np.ndarray:
    bbus = np.zeros((n_bus, n_bus))
    for line in branches:
        b = 100.0 / line.x
        bbus[line.f, line.f] += b
        bbus[line.t, line.t] += b
        bbus[line.f, line.t] -= b
        bbus[line.t, line.f] -= b
    return bbus


def _solve_hidden_ieee118_opf(
    gens: Sequence[Generator], branches: Sequence[Branch], base_load: np.ndarray,
    load_scale: float, availability: float, state_cost_scale: float,
    export_link: int | None,
) -> Tuple[float, float]:
    """Generate one observation inside the hidden external environment."""
    ng, nb = len(gens), 118
    has_q = export_link is not None
    n = ng + nb + nb + (1 if has_q else 0)  # generation, theta, shed, q
    c = np.zeros(n)
    for i, gen in enumerate(gens):
        c[i] = gen.cost * state_cost_scale
    c[ng + nb:ng + 2 * nb] = 10_000.0
    qidx = n - 1 if has_q else -1
    if has_q:
        c[qidx] = -10_000.0  # lexicographically maximize accepted injection.

    bounds: List[Tuple[float, float | None]] = []
    bounds.extend((0.0, gen.pmax * availability) for gen in gens)
    bounds.extend((0.0, 0.0) if b == 0 else (-math.pi, math.pi) for b in range(nb))
    bounds.extend((0.0, None) for _ in range(nb))
    if has_q:
        bounds.append((0.0, 800.0))

    bbus = _network_matrix(nb, branches)
    rows, cols, vals = [], [], []
    rhs = base_load * load_scale
    gens_by_bus: Dict[int, List[int]] = {}
    for i, gen in enumerate(gens):
        gens_by_bus.setdefault(gen.bus, []).append(i)
    for bus in range(nb):
        for i in gens_by_bus.get(bus, []):
            rows.append(bus); cols.append(i); vals.append(1.0)
        rows.append(bus); cols.append(ng + nb + bus); vals.append(1.0)
        for j, value in enumerate(bbus[bus]):
            if value:
                rows.append(bus); cols.append(ng + j); vals.append(-value)
        if has_q and bus == HIDDEN_ORACLE_BOUNDARY_BUSES[export_link]:
            rows.append(bus); cols.append(qidx); vals.append(1.0)
    aeq = coo_matrix((vals, (rows, cols)), shape=(nb, n)).tocsr()

    ur, uc, uv, ub = [], [], [], []
    for r, line in enumerate(branches):
        b = 100.0 / line.x
        for sign in (1.0, -1.0):
            ur.extend([len(ub), len(ub)])
            uc.extend([ng + line.f, ng + line.t])
            uv.extend([sign * b, -sign * b])
            ub.append(line.rating)
    aub = coo_matrix((uv, (ur, uc)), shape=(len(ub), n)).tocsr()
    result = linprog(c, A_ub=aub, b_ub=np.asarray(ub), A_eq=aeq,
                     b_eq=rhs, bounds=bounds, method="highs")
    if not result.success:
        raise RuntimeError(f"IEEE-118 calibration OPF failed: {result.message}")
    lmp_bus = HIDDEN_ORACLE_BOUNDARY_BUSES[export_link or 0]
    lmp = float(result.eqlin.marginals[lmp_bus])
    accepted = float(result.x[qidx]) if has_q else 0.0
    return lmp, accepted


def _generate_hidden_ieee118_observations() -> List[ExternalObservation]:
    """Use unobservable IEEE-118 truth only to generate boundary observations."""
    gens, branches, loads = _load_hidden_ieee118_truth()
    definitions = {
        "tight": (1.12, .78, 1.75),
        "loose": (.91, .92, 1.15),
    }
    profiles = {"valley": .78, "flat": .94, "peak": 1.08}
    observations: List[ExternalObservation] = []
    for state, (state_load, availability, cost_scale) in definitions.items():
        for label, shape in profiles.items():
            for link in range(4):
                price, capacity = _solve_hidden_ieee118_opf(
                    gens, branches, loads, state_load * shape,
                    availability, cost_scale, link,
                )
                # The local IEEE-118 bids are intentionally low synthetic test
                # bids. Add an explicit market-state scarcity premium instead
                # of misrepresenting their OPF marginal as a real regional LMP.
                observed_price = max(8.0, price) + (55.0 if state == "tight" else 18.0)
                # Individual transfer limits are made jointly conservative.
                observed_capacity = min(650.0, max(180.0, .62 * capacity))
                observations.append(ExternalObservation(
                    state, label, link, observed_price, observed_capacity
                ))
    return observations


def _fit_yunnan_observable_proxy(
    observations: Sequence[ExternalObservation],
) -> YunnanObservableProxy:
    """Fit the only external-data object accepted by the Yunnan optimizer."""
    envelopes: Dict[str, Dict[str, List[float]]] = {}
    for state in ("tight", "loose"):
        envelopes[state] = {}
        for label in ("valley", "flat", "peak"):
            selected = sorted(
                (obs for obs in observations
                 if obs.market_state == state and obs.load_block == label),
                key=lambda obs: obs.link,
            )
            if [obs.link for obs in selected] != list(range(4)):
                raise RuntimeError(f"incomplete observable envelope: {state}/{label}")
            envelopes[state][f"{label}_price"] = [obs.clearing_price for obs in selected]
            envelopes[state][f"{label}_capacity"] = [
                obs.accepted_export_capacity for obs in selected
            ]
    proxy = YunnanObservableProxy(envelopes)
    _validate_yunnan_information_boundary(proxy)
    return proxy


def _validate_yunnan_information_boundary(proxy: YunnanObservableProxy) -> None:
    """Reject accidental additions of hidden external data to planner input."""
    if set(vars(proxy)) != {"envelopes"}:
        raise RuntimeError("Yunnan proxy contains fields beyond observable envelopes")
    expected_keys = {
        f"{label}_{quantity}"
        for label in ("valley", "flat", "peak")
        for quantity in ("price", "capacity")
    }
    if set(proxy.envelopes) != {"tight", "loose"}:
        raise RuntimeError("Yunnan proxy must contain only inferred market states")
    for state, envelope in proxy.envelopes.items():
        if set(envelope) != expected_keys:
            raise RuntimeError(f"non-observable field in {state} external envelope")
        if any(len(values) != 4 or not np.all(np.isfinite(values))
               for values in envelope.values()):
            raise RuntimeError(f"invalid four-link observations in {state} envelope")


def build_benchmark_observable_proxy() -> YunnanObservableProxy:
    """Return public/boundary-like observations, never hidden IEEE-118 data."""
    observations = _generate_hidden_ieee118_observations()
    return _fit_yunnan_observable_proxy(observations)


def _shape_label(hour: float) -> str:
    if hour < 7 or hour >= 23:
        return "valley"
    if 17 <= hour < 23:
        return "peak"
    return "flat"


def _load_shape(hour: float) -> float:
    if hour < 6:
        return .70
    if hour < 10:
        return .82
    if hour < 17:
        return .88
    if hour < 22:
        return 1.0
    return .80


def _renewable_availability(unit: Renewable, step: Step, factor: float) -> float:
    day_factor = [1.00, .91, 1.10, 1.18, .86, .72, .68][step.day]
    if unit.kind == "solar":
        solar = max(0.0, math.sin(math.pi * (step.hour - 6.0) / 12.0))
        return min(unit.pmax, unit.pmax * solar * day_factor * factor)
    wind_shape = .48 + .16 * math.cos(2 * math.pi * (step.hour - 3.0) / 24.0)
    return min(unit.pmax, unit.pmax * wind_shape * day_factor * factor)


def _inflow_mw(day: int, factor: float) -> float:
    # Equivalent reservoir-energy inflow; MW over the represented duration.
    return [560, 520, 470, 430, 360, 310, 280][day] * factor


